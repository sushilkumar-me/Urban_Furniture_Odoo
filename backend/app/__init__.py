# app/__init__.py
#
# WHY THIS FILE EXISTS:
#   This empty file tells Python that the "app" folder is
#   a PACKAGE — meaning other files can import from it.
#
#   Without this file, Python would not recognize "app"
#   as something it can import, and lines like:
#       from app.config import settings
#   would fail with a ModuleNotFoundError.
#
# WHY IT IS EMPTY:
#   We don't need to put any code here for now.
#   Its presence alone is enough to register the package.
# ============================================================
